test("値が変わっていないかは厳密に比べる。大文字小文字、全角半角、末尾の空白だけの後からの更新も上書きしない", { skip }, async () => {
  await q(`UPDATE ITEM SET MEMO = 'ペン', NAME = N'Pen', GRADE = 'B' WHERE CODE = 'A002'`);
  const p = await prepare(client, "item", sheet([["CODE", "MEMO", "NAME", "GRADE"], ["A002", "ペン芯", "Pencil", "C"]]));
  assert.ok(p.ok, JSON.stringify(p.issues));
  assert.deepEqual(p.diff.rows[0].changes.map((c) => c.column), ["NAME", "MEMO", "GRADE"]);
  const req = buildApplyRequest(p.diff, { mode: "execute" });

  await q(`UPDATE ITEM SET MEMO = 'ﾍﾟﾝ', NAME = N'Pen ' WHERE CODE = 'A002'`);
  const conflict = await client.apply(req);
  assert.equal(conflict.error.code, "conflict");
  assert.deepEqual(conflict.conflicts.map((c) => [c.columns, c.current]), [[["NAME", "MEMO"], { MEMO: "ﾍﾟﾝ", NAME: "Pen ", GRADE: "B  " }]]);

  // 元に戻せば通る。CHAR の詰め物の空白（'B  ' と 'B'）は違いにしない。
  await q(`UPDATE ITEM SET MEMO = 'ペン', NAME = N'Pen' WHERE CODE = 'A002'`);
  const done = await client.apply({ ...req, requestId: crypto.randomUUID() });
  assert.equal(done.ok, true, JSON.stringify(done));

  // 反映の後に、大文字小文字だけ違う値へ直された行は、戻し SQL が上書きしない。
  await q(`UPDATE ITEM SET NAME = N'PENCIL' WHERE CODE = 'A002'`);
  assert.deepEqual(await runScript(done.undoScript), ["patchiri: 戻していない行（後から別の更新が入った）: CODE=A002", "patchiri: 0 / 1 行を戻しました"]);
  assert.deepEqual(await one(`SELECT MEMO, NAME, GRADE FROM ITEM WHERE CODE = 'A002'`), { MEMO: "ペン芯", NAME: "PENCIL", GRADE: "C  " });

  await q(`UPDATE ITEM SET NAME = N'Pencil' WHERE CODE = 'A002'`);
  await runScript(done.undoScript);
  assert.deepEqual(await one(`SELECT MEMO, NAME, GRADE FROM ITEM WHERE CODE = 'A002'`), { MEMO: "ペン", NAME: "Pen", GRADE: "B  " });
  await q(`UPDATE ITEM SET MEMO = NULL, NAME = N'ノート', GRADE = NULL WHERE CODE = 'A002'`);
});

