/** 生の WebMethod 呼び出し（クライアントを通さない）。 */
async function call(page, method, req) {
  const res = await fetch(`${url}/${page}/${method}`, {
    method: "POST",
    headers: { "Content-Type": "application/json; charset=utf-8", "X-Patchiri": "1" },
    body: JSON.stringify(req === undefined ? {} : { req }),
  });
  const text = await res.text();
  try {
    return JSON.parse(text).d;
  } catch {
    throw new Error(`HTTP ${res.status}: ${text.slice(0, 4000)}`);
  }
}

/** 出力した SQL の ALTER SESSION と PL/SQL ブロック（SQL*Plus の SET の行と、最後の / を除いたところ）を流し、DBMS_OUTPUT の行を返す。 */
async function runScript(script) {
  const lines = script.split("\n");
  const start = lines.findIndex((l) => l === "BEGIN" || l === "DECLARE");
  const end = lines.lastIndexOf("END;");
  assert.ok(start > 0 && end > start, script);
  assert.equal(lines[end + 1], "/");
  for (const l of lines.slice(0, start)) if (l.startsWith("ALTER SESSION ")) await admin.execute(l.replace(/;$/, ""));
  await admin.execute(`BEGIN DBMS_OUTPUT.ENABLE(NULL); END;`);
  await admin.execute(lines.slice(start, end + 1).join("\n"));
  const out = [];
  for (;;) {
    const r = await admin.execute(`BEGIN DBMS_OUTPUT.GET_LINE(:l, :s); END;`, {
      l: { dir: oracledb.BIND_OUT, type: oracledb.STRING, maxSize: 32767 },
      s: { dir: oracledb.BIND_OUT, type: oracledb.NUMBER },
    });
    if (r.outBinds.s !== 0) break;
    out.push(r.outBinds.l ?? "");
  }
  return out;
}

