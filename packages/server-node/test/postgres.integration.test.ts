  assert.ok(p.ok, JSON.stringify(p.issues));
  const req = buildApplyRequest(p.diff!, { mode: "execute" });
  await q(`UPDATE ht.ci_item SET name = 'PEN' WHERE code = 'A001'`);
  const conflict = (await client.apply(req)) as Failure;
  assert.equal(conflict.error.code, "conflict", JSON.stringify(conflict));
  await q(`UPDATE ht.ci_item SET name = 'Pen' WHERE code = 'A001'`);
  const done = (await client.apply({ ...req, requestId: crypto.randomUUID() })) as ApplyResponse;
  assert.equal(done.ok, true, JSON.stringify(done));
  await q(`UPDATE ht.ci_item SET name = 'PENCIL' WHERE code = 'A001'`);
  assert.deepEqual(await runScript(done.undoScript), ["patchiri: 戻していない行（後から別の更新が入った）: code=a001", "patchiri: 0 / 1 行を戻しました"]);
