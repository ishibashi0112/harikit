test("CHAR のキーは末尾の空白を詰めずに入れても当たる（シノニム越し）", { skip }, async () => {
  const res = await client.fetch({ target: "legacy", keys: [{ CD: "L1" }, { CD: "L22" }, { CD: "L3" }] });
  assert.deepEqual(res.rows.map((r) => (r.found ? r.values : null)), [{ CD: "L1    ", NM: "old", KANA: "ab  " }, { CD: "L22   ", NM: "old2", KANA: null }, null]);
  const p = await prepare(client, "legacy", sheet([["CD", "NM", "KANA"], ["L1", "new", "ab"], ["L22", "new2", "cd"]]));
  assert.ok(p.ok, JSON.stringify(p.issues));
  // NCHAR の詰め物の空白（'ab  ' と 'ab'）は違いにしない。
  assert.deepEqual(p.diff!.rows.map((r) => r.changes.map((c) => c.column)), [["NM"], ["NM", "KANA"]]);
  const done = (await client.apply(buildApplyRequest(p.diff!, { mode: "execute" }))) as ApplyResponse;
  assert.equal(done.ok, true, JSON.stringify(done));
  assert.deepEqual(await q(`SELECT CD, NM, KANA FROM LEGACY ORDER BY CD`), [
    { CD: "L1    ", NM: "new", KANA: "ab  " },
    { CD: "L22   ", NM: "new2", KANA: "cd  " },
  ]);
  assert.deepEqual(await runScript(done.undoScript), ["patchiri: 2 / 2 行を戻しました"]);
  assert.deepEqual(await q(`SELECT NM, KANA FROM LEGACY ORDER BY CD`), [{ NM: "old", KANA: "ab  " }, { NM: "old2", KANA: null }]);
});

test("Excel 相当の取込から反映、衝突、戻しまで", { skip }, async () => {
  const p = await prepare(
    client,
    "item",
    sheet([
      ["Code", "Price", "Big", "Stamp", "Released", "Kind_Code", "Rate"],
      ["A001", 130, "9007199254740995", { kind: "date", iso: "2026-10-18T08:00:00.000" }, "2024-04-02 10:30:00", "K2", 0.25],
      ["A002", 99.9, null, null, { kind: "date", iso: "2024-05-01T00:00:00.000" }, "K1", null],
    ]),
  );
  assert.ok(p.ok, JSON.stringify(p.issues));
  assert.deepEqual(p.diff!.counts, { change: 2, same: 0, not_found: 0 });
  assert.deepEqual(p.diff!.rows[1]!.changes.map((c) => c.column), ["PRICE", "RELEASED"]);

  const bad = await prepare(client, "item", sheet([["CODE", "KIND_CODE", "RELEASED", "QTY"], ["A001", "K9", "2024-04-02T10:30:00.5", 123456]]));
  assert.deepEqual(bad.issues.map((i) => [i.cell, i.message]), [
    ["B2", `${conn!.user.toUpperCase()}.KIND にありません`],
    ["C2", "秒の小数は 0 桁までです"],
    ["D2", "整数部は 5 桁までです"],
  ]);

  // 差分を取った後に別の人が変えたら止まる。
  await q(`UPDATE ITEM SET PRICE = 121 WHERE CODE = 'A001'`);
  const req = buildApplyRequest(p.diff!, { mode: "execute" });
  const conflict = (await client.apply(req)) as Failure;
  assert.equal(conflict.error.code, "conflict");
  assert.deepEqual(conflict.conflicts!.map((c) => [c.index, c.columns]), [[0, ["PRICE"]]]);
  assert.equal((await one(`SELECT PRICE FROM ITEM WHERE CODE = 'A002'`)).PRICE, 0.5);
  await q(`UPDATE ITEM SET PRICE = 120 WHERE CODE = 'A001'`);

  const check = (await client.apply({ ...req, mode: "check" })) as ApplyResponse;
  assert.equal(check.ok, true, JSON.stringify(check));
  await q(`DELETE FROM ITEM_AUDIT`);
  const done = (await client.apply(req)) as ApplyResponse;
  assert.equal(done.ok, true, JSON.stringify(done));
  assert.deepEqual(done.results, [{ target: "item", updated: 2 }]);
  assert.equal((await one(`SELECT COUNT(*) AS N FROM ITEM_AUDIT`)).N, 4);
  const a = await one(`SELECT TO_CHAR(PRICE) AS PRICE, TO_CHAR(BIG) AS BIG, TO_CHAR(STAMP, 'YYYY-MM-DD HH24:MI:SS.FF3') AS STAMP,
      TO_CHAR(RELEASED, 'YYYY-MM-DD HH24:MI:SS') AS RELEASED, KIND_CODE, RATE FROM ITEM WHERE CODE = 'A001'`);
  assert.deepEqual(a, { PRICE: "130", BIG: "9007199254740995", STAMP: "2026-10-18 08:00:00.000", RELEASED: "2024-04-02 10:30:00", KIND_CODE: "K2", RATE: 0.25 });
  assert.match(done.script, /^-- patchiri .* 2行 実行済み\n/);
  assert.match(done.script, /TIMESTAMP '2026-10-18 08:00:00'/);
  assert.match(done.script, /TO_DATE\('2024-04-02 10:30:00', 'YYYY-MM-DD HH24:MI:SS'\)/);

  // 戻しは、後から変わった行には触らず、その行を DBMS_OUTPUT に出す。
  await q(`UPDATE ITEM SET PRICE = 98 WHERE CODE = 'A002'`);
  assert.deepEqual(await runScript(done.undoScript), ["patchiri: 戻していない行（後から別の更新が入った）: CODE=A002", "patchiri: 1 / 2 行を戻しました"]);
  const rows = await q(`SELECT CODE, TO_CHAR(PRICE) AS PRICE, TO_CHAR(BIG) AS BIG, KIND_CODE, TO_CHAR(RELEASED, 'YYYY-MM-DD HH24:MI:SS') AS RELEASED FROM ITEM ORDER BY CODE`);
  assert.deepEqual(rows, [
    { CODE: "A001", PRICE: "120", BIG: "9007199254740993", KIND_CODE: "K1", RELEASED: "2024-04-01 00:00:00" },
    { CODE: "A002", PRICE: "98", BIG: null, KIND_CODE: "K1", RELEASED: "2024-05-01 00:00:00" },
  ]);

  // 反映の SQL は、1 行でも当たらなければ全部取り消して止まる（A002 は 98 に変わっている）。
  await assert.rejects(runScript(done.script), /ORA-20001: patchiri: 行が見つからないか、値が変わっています（CODE=A002）/);
  assert.equal((await one(`SELECT TO_CHAR(PRICE) AS PRICE FROM ITEM WHERE CODE = 'A001'`)).PRICE, "120");
  await q(`UPDATE ITEM SET PRICE = 0.5, RELEASED = NULL WHERE CODE = 'A002'`);
  await runScript(done.script);
  assert.equal((await one(`SELECT TO_CHAR(PRICE) AS PRICE FROM ITEM WHERE CODE = 'A002'`)).PRICE, "99.9");
});

test("名前に ' や & を含む値もパラメータで安全に通り、出力した SQL でも崩れない", { skip }, async () => {
  const name = "O'Reilly & Sons\"; DROP TABLE KIND;--";
  const p = await prepare(client, "item", sheet([["CODE", "NAME"], ["A002", name]]));
  assert.ok(p.ok);
  const res = (await client.apply(buildApplyRequest(p.diff!, { mode: "execute" }))) as ApplyResponse;
  assert.equal(res.ok, true, JSON.stringify(res));
  assert.equal((await one(`SELECT NAME FROM ITEM WHERE CODE = 'A002'`)).NAME, name);
  assert.match(res.undoScript, /^SET DEFINE OFF$/m);
  await runScript(res.undoScript);
  assert.equal((await one(`SELECT NAME FROM ITEM WHERE CODE = 'A002'`)).NAME, "ノート");
  await runScript(res.script);
  assert.equal((await one(`SELECT NAME FROM ITEM WHERE CODE = 'A002'`)).NAME, name);
  assert.equal((await one(`SELECT COUNT(*) AS N FROM KIND`)).N, 2);
  await q(`UPDATE ITEM SET NAME = N'ノート' WHERE CODE = 'A002'`);
});

test("空文字は NULL になるので、取込の空文字は NULL として扱い、サーバも空文字を受けない", { skip }, async () => {
  await q(`UPDATE ITEM SET NOTE = 'x' WHERE CODE = 'A001'`);
  // CSV の "" など。NULL を許す列は「空にする」差分、NOT NULL の列は必須のエラーになる。
  const p = await prepare(client, "item", sheet([["CODE", "NOTE"], ["A001", ""]]));
  assert.ok(p.ok, JSON.stringify(p.issues));
  assert.deepEqual(p.diff!.rows[0]!.changes, [{ column: "NOTE", before: "x", after: null }]);
  const bad = await prepare(client, "item", sheet([["CODE", "NAME"], ["A001", ""]]));
  assert.deepEqual(bad.issues.map((i) => [i.cell, i.message]), [["B2", "必須です（NOT NULL）"]]);
  const done = (await client.apply(buildApplyRequest(p.diff!, { mode: "execute" }))) as ApplyResponse;
  assert.equal(done.ok, true, JSON.stringify(done));
  assert.equal((await one(`SELECT NOTE FROM ITEM WHERE CODE = 'A001'`)).NOTE, null);
  // 同じものをもう一度取り込むと「同じ」になる（空文字と NULL で差分が出続けない）。
  const again = await prepare(client, "item", sheet([["CODE", "NOTE"], ["A001", ""]]));
  assert.deepEqual(again.diff!.counts, { change: 0, same: 1, not_found: 0 });
  // 戻し SQL で元の値に戻る。
  await runScript(done.undoScript);
  assert.equal((await one(`SELECT NOTE FROM ITEM WHERE CODE = 'A001'`)).NOTE, "x");
  // クライアントを通さずに空文字を送っても、サーバが弾く。
  const raw = (await client.apply({ requestId: crypto.randomUUID(), mode: "execute", changes: [{ target: "item", rows: [{ key: { CODE: "A001" }, before: { NOTE: "x" }, after: { NOTE: "" } }] }] })) as Failure;
  assert.deepEqual(raw.rowErrors!.map((e) => [e.code, e.column]), [["invalid_value", "NOTE"]]);
});

