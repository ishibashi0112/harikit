test("人が流す SQL は、流す人のセッションが大文字小文字を無視する設定でも、キーを区別して比べる", { skip }, async () => {
  await q(`INSERT INTO LEGACY VALUES ('Z1', 'up', NULL)`);
  await q(`INSERT INTO LEGACY VALUES ('z1', 'low', NULL)`);
  try {
    const p = await prepare(client, "legacy", sheet([["CD", "NM"], ["Z1", "UP"]]));
    assert.ok(p.ok, JSON.stringify(p.issues));
    const done = (await client.apply(buildApplyRequest(p.diff!, { mode: "execute" }))) as ApplyResponse;
    assert.equal(done.ok, true, JSON.stringify(done));
    // 小文字のキーの行も、たまたま同じ値になった。NLS_COMP = LINGUISTIC のままだと、戻し SQL がこの行にも当たる。
    await q(`UPDATE LEGACY SET NM = 'UP' WHERE CD = 'z1'`);
    await admin.execute(`ALTER SESSION SET NLS_COMP = 'LINGUISTIC' NLS_SORT = 'BINARY_CI'`);
    assert.deepEqual(await runScript(done.undoScript), ["patchiri: 1 / 1 行を戻しました"]);
    assert.deepEqual(await q(`SELECT CD, NM FROM LEGACY WHERE CD IN ('Z1', 'z1') ORDER BY CD`), [
      { CD: "Z1    ", NM: "up" },
      { CD: "z1    ", NM: "UP" },
    ]);
  } finally {
    await admin.execute(`ALTER SESSION SET NLS_COMP = 'BINARY' NLS_SORT = 'BINARY'`);
    await q(`DELETE FROM LEGACY WHERE CD IN ('Z1', 'z1')`);
  }
});

test("改行や、/ や . だけの行、# で始まる行を含む値、長い値も、出力した SQL で崩れない", { skip }, async () => {
  // SQL*Plus は文字列の中でも / や . だけの行を文の終わり、# で始まる行をコマンドとして読むので、改行は CHR / UNISTR で書く。
  const nm = "a\r\n/\n#x\n.\nb";
  const kana = "ア\nイ";
  const remark = "あ".repeat(150) + "\n" + "b".repeat(120);
  const before = { L1: await one(`SELECT NM, KANA FROM LEGACY WHERE CD = 'L1'`), A002: await one(`SELECT REMARK FROM ITEM WHERE CODE = 'A002'`) };
  const p1 = await prepare(client, "legacy", sheet([["CD", "NM", "KANA"], ["L1", nm, kana]]));
  assert.ok(p1.ok, JSON.stringify(p1.issues));
  const d1 = (await client.apply(buildApplyRequest(p1.diff!, { mode: "execute" }))) as ApplyResponse;
  assert.equal(d1.ok, true, JSON.stringify(d1));
  const p2 = await prepare(client, "item", sheet([["CODE", "REMARK"], ["A002", remark]]));
  assert.ok(p2.ok, JSON.stringify(p2.issues));
  const d2 = (await client.apply(buildApplyRequest(p2.diff!, { mode: "execute" }))) as ApplyResponse;
  assert.equal(d2.ok, true, JSON.stringify(d2));
  for (const script of [d1.script, d1.undoScript, d2.script, d2.undoScript]) {
    const lines = script.split("\n");
    assert.deepEqual(lines.filter((l) => /^\s*[/.]\s*$/.test(l) || /^\s*#/.test(l)), ["/"]);
    assert.ok(lines.every((l) => l.length < 1000));
  }

  assert.deepEqual(await runScript(d1.undoScript), ["patchiri: 1 / 1 行を戻しました"]);
  assert.deepEqual(await runScript(d2.undoScript), ["patchiri: 1 / 1 行を戻しました"]);
  assert.deepEqual(await one(`SELECT NM, KANA FROM LEGACY WHERE CD = 'L1'`), before.L1);
  assert.deepEqual(await one(`SELECT REMARK FROM ITEM WHERE CODE = 'A002'`), before.A002);
  await runScript(d1.script);
  await runScript(d2.script);
  assert.deepEqual(await one(`SELECT NM, KANA FROM LEGACY WHERE CD = 'L1'`), { NM: nm, KANA: kana + " " });
  assert.deepEqual(await one(`SELECT REMARK FROM ITEM WHERE CODE = 'A002'`), { REMARK: remark });
  // 流し直すと、値が変わっていないので戻しが当たる（比べ方も崩れていない）。
  assert.deepEqual(await runScript(d1.undoScript), ["patchiri: 1 / 1 行を戻しました"]);
  assert.deepEqual(await runScript(d2.undoScript), ["patchiri: 1 / 1 行を戻しました"]);
});

